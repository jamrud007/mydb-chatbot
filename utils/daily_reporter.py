"""
Daily Reporter Utility
Generates daily activity reports and persists metrics
"""
import os
import json
import logging
from datetime import datetime
from typing import Dict, Optional
from config import Config
from utils.metrics import get_metrics_collector

logger = logging.getLogger(__name__)

class DailyReporter:
    """
    Handles daily reporting and metrics persistence
    """
    
    def __init__(self, base_dir: str = "data/daily_reports"):
        self.base_dir = base_dir
        self.reports_dir = os.path.join(base_dir, "markdown")
        self.metrics_dir = os.path.join(base_dir, "metrics")
        
        # Create directories
        os.makedirs(self.reports_dir, exist_ok=True)
        os.makedirs(self.metrics_dir, exist_ok=True)
        
    def save_daily_metrics(self) -> str:
        """
        Save current metrics to JSON file
        
        Returns:
            str: Path to saved metrics file
        """
        metrics = get_metrics_collector().get_all_metrics()
        
        # Add timestamp
        today = datetime.now().strftime("%Y-%m-%d")
        filename = f"metrics_{today}.json"
        filepath = os.path.join(self.metrics_dir, filename)
        
        try:
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(metrics, f, indent=2, default=str)
            logger.info(f"Daily metrics saved to {filepath}")
            return filepath
        except Exception as e:
            logger.error(f"Failed to save metrics: {e}")
            raise

    def generate_daily_report(self) -> str:
        """
        Generate markdown report for the day
        
        Returns:
            str: Path to generated markdown report
        """
        # First ensure metrics are saved
        self.save_daily_metrics()
        
        metrics = get_metrics_collector().get_all_metrics()
        today = datetime.now().strftime("%Y-%m-%d")
        
        report_content = self._format_markdown_report(today, metrics)
        
        filename = f"report_{today}.md"
        filepath = os.path.join(self.reports_dir, filename)
        
        try:
            with open(filepath, 'w', encoding='utf-8') as f:
                f.write(report_content)
            logger.info(f"Daily report generated at {filepath}")
            return filepath
        except Exception as e:
            logger.error(f"Failed to generate report: {e}")
            raise

    def _format_markdown_report(self, date: str, metrics: Dict) -> str:
        """Format metrics into a beautiful markdown report"""
        
        query_stats = metrics.get('query_performance', {})
        usage_stats = metrics.get('usage', {})
        error_stats = metrics.get('errors', {})
        llm_stats = metrics.get('llm', {})
        
        # Calculate success rate
        total_q = query_stats.get('total_queries', 0)
        total_err = error_stats.get('total_errors', 0)
        success_rate = ((total_q - total_err) / total_q * 100) if total_q > 0 else 100
        
        lines = []
        lines.append(f"# 📊 Daily System Report - {date}")
        lines.append("")
        lines.append("## 🚀 Performance Overview")
        lines.append("| Metric | Value | Status |")
        lines.append("|---|---|---|")
        lines.append(f"| **Total Queries** | `{total_q}` | - |")
        lines.append(f"| **Success Rate** | `{success_rate:.1f}%` | {'✅' if success_rate > 95 else '⚠️'} |")
        lines.append(f"| **Avg Latency** | `{query_stats.get('avg_duration_ms', 0)}ms` | - |")
        lines.append(f"| **Active Users** | `{usage_stats.get('total_users', 0)}` | - |")
        lines.append("")
        
        lines.append("## ⏱️ Query Execution")
        lines.append(f"- **P95 Latency:** `{query_stats.get('p95_duration_ms', 0)}ms`")
        lines.append(f"- **P99 Latency:** `{query_stats.get('p99_duration_ms', 0)}ms`")
        lines.append(f"- **Slow Queries (>5s):** `{query_stats.get('slow_query_count', 0)}`")
        lines.append("")
        
        lines.append("## 🤖 AI / LLM Performance")
        lines.append(f"- **Total Calls:** `{llm_stats.get('total_calls', 0)}`")
        lines.append(f"- **Avg Generation:** `{llm_stats.get('avg_duration_ms', 0)}ms`")
        lines.append(f"- **Failures:** `{llm_stats.get('failures', 0)}`")
        lines.append("")
        
        if error_stats.get('errors_by_type'):
            lines.append("## ⚠️ Error Breakdown")
            lines.append("```json")
            lines.append(json.dumps(error_stats['errors_by_type'], indent=2))
            lines.append("```")
            lines.append("")
            
        lines.append("---")
        lines.append(f"*Generated by Auto-Reporter at {datetime.now().strftime('%H:%M:%S')}*")
        
        return "\n".join(lines)

# Singleton
_daily_reporter = None

def get_daily_reporter():
    global _daily_reporter
    if _daily_reporter is None:
        _daily_reporter = DailyReporter()
    return _daily_reporter
