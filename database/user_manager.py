"""
User Management Module
Handles user CRUD operations, password hashing, and authentication
Supports MySQL and Oracle.
"""
import logging
from datetime import datetime
from typing import Optional, Dict, List

import bcrypt

try:
    import mysql.connector
except Exception:  # pragma: no cover - optional path
    mysql = None

logger = logging.getLogger(__name__)


class UserManager:
    """Manages user operations in database"""

    def __init__(self, db_connection):
        """
        Initialize UserManager

        Args:
            db_connection: DatabaseConnection instance
        """
        self.db_connection = db_connection
        self.engine = getattr(db_connection, 'engine', 'mysql').lower()
        # Use a separate table on Oracle to avoid collision with the existing USERS table
        self._tbl = "chatbot_users" if self.engine == "oracle" else "users"
        self._create_users_table()

    def _adapt_query(self, query: str) -> str:
        """Substitute table name and convert %s placeholders for Oracle."""
        import re
        query = re.sub(r'\busers\b', self._tbl, query)
        if self.engine != 'oracle':
            return query
        idx = 0
        while '%s' in query:
            idx += 1
            query = query.replace('%s', f':{idx}', 1)
        return query

    @staticmethod
    def _row_to_dict(cursor, row):
        if row is None:
            return None
        columns = [desc[0].lower() for desc in cursor.description]
        return {columns[i]: row[i] for i in range(len(columns))}

    def _create_users_table(self):
        """Create users table if it doesn't exist"""
        create_mysql = """
        CREATE TABLE IF NOT EXISTS users (
            id INT AUTO_INCREMENT PRIMARY KEY,
            username VARCHAR(50) UNIQUE NOT NULL,
            email VARCHAR(100) UNIQUE NOT NULL,
            hashed_password VARCHAR(255) NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            last_login TIMESTAMP NULL,
            is_active BOOLEAN DEFAULT TRUE,
            is_verified BOOLEAN DEFAULT FALSE,
            verification_code VARCHAR(6),
            INDEX idx_username (username),
            INDEX idx_email (email)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
        """

        create_oracle = f"""
        BEGIN
            EXECUTE IMMEDIATE '
                CREATE TABLE {self._tbl} (
                    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                    username VARCHAR2(50) UNIQUE NOT NULL,
                    email VARCHAR2(100) UNIQUE NOT NULL,
                    hashed_password VARCHAR2(255) NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    last_login TIMESTAMP NULL,
                    is_active NUMBER(1) DEFAULT 1 NOT NULL,
                    is_verified NUMBER(1) DEFAULT 0 NOT NULL,
                    verification_code VARCHAR2(6)
                )
            ';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -955 THEN
                    RAISE;
                END IF;
        END;
        """

        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()
            cursor.execute(create_oracle if self.engine == 'oracle' else create_mysql)
            conn.commit()
            logger.info("Users table created or already exists")
        except Exception as e:
            logger.error(f"Failed to create users table: {e}")
            raise
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def _hash_password(self, password: str) -> str:
        """Hash password using bcrypt."""
        salt = bcrypt.gensalt()
        hashed = bcrypt.hashpw(password.encode('utf-8'), salt)
        return hashed.decode('utf-8')

    def _verify_password(self, plain_password: str, hashed_password: str) -> bool:
        """Verify password against hash."""
        return bcrypt.checkpw(plain_password.encode('utf-8'), hashed_password.encode('utf-8'))

    def create_user(self, username: str, email: str, password: str, verification_code: str = None) -> Optional[int]:
        """Create a new user and return user id."""
        conn = None
        cursor = None
        try:
            hashed_password = self._hash_password(password)

            conn = self.db_connection.get_connection()
            cursor = conn.cursor()

            insert_query = """
            INSERT INTO users (username, email, hashed_password, verification_code, is_verified)
            VALUES (%s, %s, %s, %s, %s)
            """
            params = (username, email, hashed_password, verification_code, 0 if self.engine == 'oracle' else False)
            cursor.execute(self._adapt_query(insert_query), params)
            conn.commit()

            # Cross-engine safe way to fetch created id
            created = self.get_user_by_username(username)
            user_id = int(created['id']) if created else None
            logger.info(f"User created successfully: {username} (ID: {user_id})")
            return user_id

        except Exception as e:
            msg = str(e).lower()
            if "duplicate" in msg or "unique" in msg or "ora-00001" in msg:
                logger.warning(f"User creation failed - duplicate entry: {e}")
                return None
            logger.error(f"Failed to create user: {e}")
            return None
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def get_user_by_username(self, username: str) -> Optional[Dict]:
        """Get user by username."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()

            select_query = """
            SELECT id, username, email, hashed_password, created_at, last_login, is_active, is_verified
            FROM users
            WHERE username = %s AND is_active = %s
            """
            active_val = 1 if self.engine == 'oracle' else True
            cursor.execute(self._adapt_query(select_query), (username, active_val))
            return self._row_to_dict(cursor, cursor.fetchone())
        except Exception as e:
            logger.error(f"Failed to get user by username: {e}")
            return None
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def get_user_by_email(self, email: str) -> Optional[Dict]:
        """Get user by email."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()

            select_query = """
            SELECT id, username, email, hashed_password, created_at, last_login, is_active, is_verified
            FROM users
            WHERE email = %s AND is_active = %s
            """
            active_val = 1 if self.engine == 'oracle' else True
            cursor.execute(self._adapt_query(select_query), (email, active_val))
            return self._row_to_dict(cursor, cursor.fetchone())
        except Exception as e:
            logger.error(f"Failed to get user by email: {e}")
            return None
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def get_user_by_id(self, user_id: int) -> Optional[Dict]:
        """Get user by ID."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()

            select_query = """
            SELECT id, username, email, created_at, last_login, is_active
            FROM users
            WHERE id = %s AND is_active = %s
            """
            active_val = 1 if self.engine == 'oracle' else True
            cursor.execute(self._adapt_query(select_query), (user_id, active_val))
            return self._row_to_dict(cursor, cursor.fetchone())
        except Exception as e:
            logger.error(f"Failed to get user by ID: {e}")
            return None
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def authenticate_user(self, username_or_email: str, password: str) -> Optional[Dict]:
        """Authenticate user with username/email and password."""
        user = self.get_user_by_username(username_or_email)
        if not user:
            user = self.get_user_by_email(username_or_email)

        if not user:
            logger.warning(f"Authentication failed - user not found: {username_or_email}")
            return None

        if not self._verify_password(password, user['hashed_password']):
            logger.warning(f"Authentication failed - invalid password for: {username_or_email}")
            return None

        if not user.get('is_verified'):
            logger.warning(f"Authentication failed - email not verified: {username_or_email}")
            return {'error': 'not_verified', 'email': user['email']}

        self.update_last_login(int(user['id']))

        user_data = {
            'id': int(user['id']),
            'username': user['username'],
            'email': user['email'],
            'created_at': user['created_at'],
            'last_login': user['last_login']
        }
        logger.info(f"User authenticated successfully: {username_or_email}")
        return user_data

    def update_last_login(self, user_id: int) -> bool:
        """Update user's last login timestamp."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()
            update_query = "UPDATE users SET last_login = %s WHERE id = %s"
            cursor.execute(self._adapt_query(update_query), (datetime.now(), user_id))
            conn.commit()
            return True
        except Exception as e:
            logger.error(f"Failed to update last login: {e}")
            return False
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def update_password(self, user_id: int, new_password: str) -> bool:
        """Update user's password."""
        conn = None
        cursor = None
        try:
            hashed_password = self._hash_password(new_password)
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()
            update_query = "UPDATE users SET hashed_password = %s WHERE id = %s"
            cursor.execute(self._adapt_query(update_query), (hashed_password, user_id))
            conn.commit()
            logger.info(f"Password updated for user ID: {user_id}")
            return True
        except Exception as e:
            logger.error(f"Failed to update password: {e}")
            return False
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def delete_user(self, user_id: int) -> bool:
        """Soft delete user."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()
            update_query = "UPDATE users SET is_active = %s WHERE id = %s"
            inactive_val = 0 if self.engine == 'oracle' else False
            cursor.execute(self._adapt_query(update_query), (inactive_val, user_id))
            conn.commit()
            logger.info(f"User soft deleted: {user_id}")
            return True
        except Exception as e:
            logger.error(f"Failed to delete user: {e}")
            return False
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def get_all_users(self) -> List[Dict]:
        """Get all active users (without passwords)."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()
            active_val = 1 if self.engine == 'oracle' else True
            select_query = """
            SELECT id, username, email, created_at, last_login
            FROM users
            WHERE is_active = %s
            ORDER BY created_at DESC
            """
            cursor.execute(self._adapt_query(select_query), (active_val,))
            rows = cursor.fetchall()
            return [self._row_to_dict(cursor, row) for row in rows]
        except Exception as e:
            logger.error(f"Failed to get all users: {e}")
            return []
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()

    def verify_user_email(self, email: str, code: str) -> bool:
        """Verify user email with OTP code."""
        conn = None
        cursor = None
        try:
            conn = self.db_connection.get_connection()
            cursor = conn.cursor()

            query = "SELECT id FROM users WHERE email = %s AND verification_code = %s"
            cursor.execute(self._adapt_query(query), (email, code))
            result = cursor.fetchone()
            if not result:
                return False

            user_id = result[0]
            update = "UPDATE users SET is_verified = %s, verification_code = %s WHERE id = %s"
            verified_val = 1 if self.engine == 'oracle' else True
            cursor.execute(self._adapt_query(update), (verified_val, None, user_id))
            conn.commit()
            return True
        except Exception as e:
            logger.error(f"Verification failed: {e}")
            return False
        finally:
            if cursor:
                cursor.close()
            if conn:
                conn.close()
